import { sql } from "drizzle-orm";
import { index, integer, primaryKey, sqliteTable, text } from "drizzle-orm/sqlite-core";
import type { Participant, ThreadAction } from "@mailfast/shared";

/**
 * Local metadata cache. Every UI read is served from here, so list views and
 * search never wait on Gmail. Threads are derived from messages and kept
 * denormalised (threads + thread_labels) so a label page is one indexed scan.
 *
 * The FTS5 table `messages_fts` is created by a custom migration because
 * Drizzle has no virtual-table support; its rowid matches `messages.rowid`.
 */

export const kv = sqliteTable("kv", {
  key: text("key").primaryKey(),
  value: text("value").notNull(),
});

export const messages = sqliteTable(
  "messages",
  {
    // Implicit SQLite rowid is kept (no WITHOUT ROWID) and used as the FTS rowid.
    id: text("id").primaryKey(),
    threadId: text("thread_id").notNull(),
    internalDate: integer("internal_date").notNull(),
    fromName: text("from_name").notNull(),
    fromEmail: text("from_email").notNull(),
    to: text("to_addr").notNull(),
    cc: text("cc_addr").notNull(),
    subject: text("subject").notNull(),
    snippet: text("snippet").notNull(),
    labelIds: text("label_ids", { mode: "json" }).$type<string[]>().notNull(),
  },
  (t) => [index("messages_thread").on(t.threadId, t.internalDate)],
);

export const threads = sqliteTable("threads", {
  id: text("id").primaryKey(),
  lastDate: integer("last_date").notNull(),
  subject: text("subject").notNull(),
  snippet: text("snippet").notNull(),
  senders: text("senders", { mode: "json" }).$type<Participant[]>().notNull(),
  messageCount: integer("message_count").notNull(),
  unread: integer("unread", { mode: "boolean" }).notNull(),
  starred: integer("starred", { mode: "boolean" }).notNull(),
  important: integer("important", { mode: "boolean" }).notNull(),
  labelIds: text("label_ids", { mode: "json" }).$type<string[]>().notNull(),
  /** Every message of the thread is known locally (fetched via threads.get or backfill finished). */
  complete: integer("complete", { mode: "boolean" }).notNull().default(false),
});

export const threadLabels = sqliteTable(
  "thread_labels",
  {
    labelId: text("label_id").notNull(),
    threadId: text("thread_id").notNull(),
    lastDate: integer("last_date").notNull(),
  },
  (t) => [
    primaryKey({ columns: [t.labelId, t.threadId] }),
    index("thread_labels_page").on(t.labelId, sql`${t.lastDate} DESC`),
    index("thread_labels_thread").on(t.threadId),
  ],
);

export const labels = sqliteTable("labels", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  type: text("type", { enum: ["system", "user"] }).notNull(),
  color: text("color"),
  unread: integer("unread").notNull().default(0),
  total: integer("total").notNull().default(0),
});

/** Optimistic actions waiting to be pushed to Gmail. Survives restarts. */
export const outbox = sqliteTable("outbox", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  threadId: text("thread_id").notNull(),
  action: text("action", { mode: "json" }).$type<ThreadAction>().notNull(),
  attempts: integer("attempts").notNull().default(0),
  nextAt: integer("next_at").notNull().default(0),
  lastError: text("last_error"),
});

